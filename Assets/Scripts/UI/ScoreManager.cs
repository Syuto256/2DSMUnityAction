// ============================================================
// ScoreManager
// スコアを保存しておく場所です。
//
// 【重要】
//  このクラスはオブジェクトに付けません（static クラスのため）。
//  SceneLoader と同じ仕組みです。
//  他のスクリプトから ScoreManager.AddScore(1); のように直接呼びます。
//
// 【なぜ static なのか】
//  シーンをまたいでも値が消えないためです。
//  ゲーム画面でためたスコアを、クリア画面でも表示できます。
// ============================================================

public static class ScoreManager
{
    // 現在のスコア。読むのは自由、書き換えはこの中のメソッドからだけ
    public static int CurrentScore { get; private set; }

    // ------------------------------------------------------------
    // スコアを増やす（Coin から呼ばれる）
    // ------------------------------------------------------------
    public static void AddScore(int amount)
    {
        CurrentScore += amount;
        UnityEngine.Debug.Log("スコア: " + CurrentScore);
    }

    // ------------------------------------------------------------
    // スコアを 0 に戻す
    // ゲームを始め直すときに SceneLoader から呼ばれます
    // ------------------------------------------------------------
    public static void ResetScore()
    {
        CurrentScore = 0;
    }
}
